create or replace function public.is_trek_admin(candidate uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = candidate and role = 'admin' and status = 'active'
  );
$$;

create or replace function public.is_workspace_member(candidate_workspace uuid, candidate_user uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.workspace_members
    where workspace_id = candidate_workspace and user_id = candidate_user
  );
$$;

revoke all on function public.is_trek_admin(uuid) from public;
revoke all on function public.is_workspace_member(uuid, uuid) from public;
grant execute on function public.is_trek_admin(uuid) to authenticated;
grant execute on function public.is_workspace_member(uuid, uuid) to authenticated;

alter table public.profiles enable row level security;
alter table public.workspaces enable row level security;
alter table public.workspace_members enable row level security;

create policy profiles_select_own_or_admin
on public.profiles for select to authenticated
using (id = auth.uid() or public.is_trek_admin(auth.uid()));

create policy workspaces_select_member_or_admin
on public.workspaces for select to authenticated
using (public.is_workspace_member(id, auth.uid()) or public.is_trek_admin(auth.uid()));

create policy workspace_members_select_member_or_admin
on public.workspace_members for select to authenticated
using (public.is_workspace_member(workspace_id, auth.uid()) or public.is_trek_admin(auth.uid()));

-- No direct client writes in phase one. Profile and membership mutations go
-- through authenticated Edge Functions after server-side role validation.
revoke all on public.profiles, public.workspaces, public.workspace_members from anon;
grant select on public.profiles, public.workspaces, public.workspace_members to authenticated;
